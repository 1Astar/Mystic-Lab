/**
 * 六十四卦判词卡：本/变义、隐喻、定调、问事翻译、决策底句
 * 教学口语，非逐字考证；供 OfflineAnswerPack / direct-reading 优先读取
 */

export type HexVoice = {
  /** 本卦气质短标 */
  frame: string;
  /** 作变卦时的走向短标 */
  asChanged: string;
  /** 单卦核心隐喻 */
  metaphorSolo: string;
  /** 有变卦时：可用 {from}{to} */
  metaphorTo: string;
  /** 无特殊意图时的定调句；可用 {from}{to} */
  verdict: string;
  /** 对应问题：本卦怎么译回人事 */
  mapAsk: string;
  /** 变卦对应问题 */
  mapAskChanged: string;
  /** 决策底句（三行） */
  decision: string;
};

function v(
  frame: string,
  asChanged: string,
  metaphorSolo: string,
  metaphorTo: string,
  verdict: string,
  mapAsk: string,
  mapAskChanged: string,
  decision: string,
): HexVoice {
  return {
    frame,
    asChanged,
    metaphorSolo,
    metaphorTo,
    verdict,
    mapAsk,
    mapAskChanged,
    decision,
  };
}

