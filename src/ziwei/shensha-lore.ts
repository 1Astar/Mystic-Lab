export const SHENSHA_LORE: ShenshaLore[] = [
  ...ADJECTIVE,
  ...CHANGSHENG,
  ...BOSHI,
  ...JIANGQIAN,
  ...SUIQIAN,
];

const byId = new Map<string, ShenshaLore>();
const byAlias = new Map<string, ShenshaLore>();

function indexAll(): void {
  if (byId.size) return;
  for (const s of SHENSHA_LORE) {
    if (!byId.has(s.id)) byId.set(s.id, s);
    byAlias.set(s.id, s);
    for (const a of s.aliases ?? []) byAlias.set(a, s);
  }
}

export function getShenshaLore(name: string): ShenshaLore | undefined {
  indexAll();
  const key = name.replace(/星$/, '').trim();
  return byAlias.get(key) ?? byId.get(key);
}

export function listShenshaLore(): ShenshaLore[] {
  return [...SHENSHA_LORE];
}

export function listShenshaByGroup(
  group: NonNullable<ShenshaLore['group']>,
): ShenshaLore[] {
  return SHENSHA_LORE.filter((s) => s.group === group);
}
