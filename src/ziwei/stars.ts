export const CODEX_STARS: StarCard[] = [
  ...MAJOR_STARS,
  ...AUX_STARS,
  ...MUTAGEN_STARS,
];

export const CODEX_STAR_IDS = CODEX_STARS.map((s) => s.id);
export const MAJOR_STAR_IDS = MAJOR_STARS.map((s) => s.id as MajorStarId);

/** 兼容旧名 */
export type MajorStarLore = StarCard;
export type StarLore = StarCard;

export function getStarLore(name: string): StarCard | undefined {
  const exact = CODEX_STARS.find((s) => s.id === name);
  if (exact) return exact;
  return CODEX_STARS.find((s) => name.startsWith(s.id));
}

export function isMajorStar(name: string): name is MajorStarId {
  return MAJOR_STAR_IDS.includes(name as MajorStarId);
}

export function isCodexStar(name: string): boolean {
  return Boolean(getStarLore(name));
}

export function codexStarsByCategory(cat: StarCategory): StarCard[] {
  return CODEX_STARS.filter((s) => s.category === cat);
}

export function majorsByGroup(group: MajorGroup): StarCard[] {
  return MAJOR_STARS.filter((s) => s.majorGroup === group);
}

/** 生年四化名 → 图鉴卡 id */
export function mutagenToCardId(mutagen: string): string | null {
  if (mutagen === '禄') return '化禄';
  if (mutagen === '权') return '化权';
  if (mutagen === '科') return '化科';
  if (mutagen === '忌') return '化忌';
  return null;
}
