export function mutagenNoteForStar(starId: string, kind: MutagenKind): string {
  const key = starId.replace(/星$/, '');
  const special = MAJOR_NOTES[key]?.[kind];
  if (special) return special;
  return GENERIC[kind].replace(/\{star\}/g, key);
}

export function allMutagenNotesForStar(starId: string): Array<{ kind: MutagenKind; text: string }> {
  return (['禄', '权', '科', '忌'] as MutagenKind[]).map((kind) => ({
    kind,
    text: mutagenNoteForStar(starId, kind),
  }));
}
