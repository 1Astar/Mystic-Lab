/** 合成兜底：可读，但不冒充手写精品 */
export function composeJiaziDayunFallback(gz: string): JiaziDayunLore {
  const stem = gz.charAt(0);
  const branch = gz.charAt(1);
  const ny = nayinOf(gz);
  const lore = getNayinLore(ny);
  const scene = lore?.scene || `纳音${ny}的气象画面`;
  const temper = lore?.temperament || '合干支与纳音看气质';
  return {
    theme: `${gz}十年 · ${ny}气象（详解待补）`,
    weather: `作大运时：${scene} 天干${stem}、地支${branch}共同塑造这十年的主滤镜。${temper}`,
    leanIn:
      lore?.need?.slice(0, 2).join('；') ||
      `合读天干「${stem}」、地支「${branch}」与原局十神，找可推进的主轴。`,
    watch:
      lore?.imbalance ||
      '勿单凭甲子名断吉凶；忌忽略日主强弱与流年冲合。',
    playbook: `先当「十年滤镜」用：对照原局哪一柱被触发，再决定加速还是护盘。完整「${gz}」大运专篇将逐步补全。`,
    memory: `${gz}大运 = ${stem}+${branch} · ${ny}（兜底）。合原局，勿单断。`,
    rich: false,
  };
}

export function getJiaziDayunLore(gz: string): JiaziDayunLore {
  const rich = getJiaziDayunLoreRich(gz);
  if (rich) return { ...rich, rich: true };
  return composeJiaziDayunFallback(gz);
}

/** 覆盖率：手写条数 / 60 */
export function jiaziDayunRichCoverage(): { rich: number; total: number } {
  return { rich: listRichJiaziDayunIds().length, total: listSixtyJiazi().length };
}

/** 穿梭 tip / 盘面悬停：十年主题 */
export function dayunLoreHint(gz: string): string {
  if (!gz || gz.length < 2) return '';
  return getJiaziDayunLore(gz).theme;
}

/** 穿梭「这段大运」/ 盘面当前大运旁白 */
export function dayunLoreDecadeNote(gz: string): string {
  if (!gz || gz.length < 2) return '';
  const l = getJiaziDayunLore(gz);
  return `这段大运 · ${l.theme}。${l.weather} 宜：${l.leanIn} 留意：${l.watch}`;
}

/** 生命结构阶段正文 */
export function dayunLoreStageTopic(gz: string): string {
  if (!gz || gz.length < 2) return '';
  const l = getJiaziDayunLore(gz);
  return `${l.theme}。${l.playbook}`;
}
